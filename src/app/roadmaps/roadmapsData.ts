// Helper to look up any roadmap course by code, slug, title, or url
export function findRoadmapCourse(codeOrSlugOrTitle: string): RoadmapCourse | undefined {
  if (!codeOrSlugOrTitle) return undefined;
  const query = codeOrSlugOrTitle.toLowerCase().trim().replace(/^\/domains\//, '');
  
  // 1. Exact match on code or slug
  for (const domain of ROADMAP_DOMAINS) {
    const found = domain.courses.find(
      (c) => c.code.toLowerCase() === query || c.slug.toLowerCase() === query
    );
    if (found) return found;
  }

  // 2. Exact match on title or url
  for (const domain of ROADMAP_DOMAINS) {
    const found = domain.courses.find(
      (c) => c.title.toLowerCase() === query || c.url.toLowerCase().includes(query)
    );
    if (found) return found;
  }

  // 3. Partial/contains match on title
  for (const domain of ROADMAP_DOMAINS) {
    const found = domain.courses.find(
      (c) => c.title.toLowerCase().includes(query) || query.includes(c.title.toLowerCase())
    );
    if (found) return found;
  }

  return undefined;
}

// Pro Plan is strictly exclusive to HRM, Data Analytics, and Data Science
export function isProPlanEligible(courseOrCodeOrSlug: RoadmapCourse | string | undefined | null): boolean {
  if (!courseOrCodeOrSlug) return false;
  let text = '';
  if (typeof courseOrCodeOrSlug === 'string') {
    text = courseOrCodeOrSlug.toLowerCase().trim();
  } else {
    text = `${courseOrCodeOrSlug.code} ${courseOrCodeOrSlug.slug} ${courseOrCodeOrSlug.title} ${courseOrCodeOrSlug.domainId}`.toLowerCase();
  }

  // 1. Exact course codes
  // C10 = Data Analytics, C12 = Data Science, C68 = Human Resources (HR)
  // C91 = Data Science (Job Guarantee), C92 = Data Analytics (Job Guarantee), C93 = HRM (Job Guarantee)
  if (
    text === 'c10' ||
    text === 'c12' ||
    text === 'c68' ||
    text === 'c91' ||
    text === 'c92' ||
    text === 'c93' ||
    text.includes('c10 ') ||
    text.includes('c12 ') ||
    text.includes('c68 ') ||
    text.includes('c91 ') ||
    text.includes('c92 ') ||
    text.includes('c93 ')
  ) {
    return true;
  }

  // 2. Keyword checks for HRM, Data Analytics, Data Science
  if (
    text.includes('data-science') ||
    text.includes('data science') ||
    text.includes('data-analytics') ||
    text.includes('data analytics') ||
    text.includes('hrm') ||
    text.includes('human-resource') ||
    text.includes('human resource')
  ) {
    return true;
  }

  return false;
}
